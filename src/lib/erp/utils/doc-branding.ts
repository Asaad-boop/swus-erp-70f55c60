/**
 * Shared branding used on every printable / PDF document produced by the ERP
 * (reports, invoices, payslips, statements...).
 *
 * It is a tiny module-level store (mirrored to localStorage) so that plain
 * helper functions like `printHtml` can render a branded header + footer
 * without every caller having to thread company data through.
 */

export type DocBranding = {
  company: string;
  tagline: string;
  logoUrl: string;
  address: string;
  phone: string;
  email: string;
  website: string;
  bin: string;
  footerNote: string;
};

export const DEFAULT_DOC_BRANDING: DocBranding = {
  company: "Synq With Us",
  tagline: "",
  logoUrl: "",
  address: "",
  phone: "",
  email: "",
  website: "",
  bin: "",
  footerNote: "Confidential — generated by Synq With Us ERP.",
};

const STORAGE_KEY = "erp.docBranding";

let current: DocBranding = { ...DEFAULT_DOC_BRANDING };

if (typeof window !== "undefined") {
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (raw) current = { ...DEFAULT_DOC_BRANDING, ...(JSON.parse(raw) as Partial<DocBranding>) };
  } catch {
    /* ignore */
  }
}

export function getDocBranding(): DocBranding {
  return current;
}

export function setDocBranding(patch: Partial<DocBranding>) {
  current = { ...current, ...patch };
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(STORAGE_KEY, JSON.stringify(current));
    } catch {
      /* ignore */
    }
  }
  return current;
}
