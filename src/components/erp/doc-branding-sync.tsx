import { useEffect } from "react";
import { useQuery } from "@tanstack/react-query";
import { getAppSetting } from "@/lib/erp/settings/app-settings.functions";
import { mergeCompany } from "@/lib/erp/hr/company";
import { useBrand } from "@/contexts/brand-context";
import { setDocBranding } from "@/lib/erp/utils/doc-branding";

/**
 * Keeps the shared PDF/print branding (logo, company, contact, footer)
 * in sync with HR company settings + the active brand. Mount once inside
 * the ERP layout.
 */
export function DocBrandingSync() {
  const { activeBrand } = useBrand();
  const { data } = useQuery({
    queryKey: ["hr-company"],
    queryFn: () => getAppSetting({ data: { key: "hr_company" } }),
    staleTime: 10 * 60 * 1000,
  });

  useEffect(() => {
    const c = mergeCompany(data?.value);
    setDocBranding({
      company: activeBrand?.name || c.name || "Synq With Us",
      logoUrl: activeBrand?.logo_url || c.logo_url || "",
      address: c.address,
      phone: c.phone,
      email: c.email,
      website: c.website,
      bin: c.bin,
      footerNote: c.footer_note || "Confidential — generated by Synq With Us ERP.",
    });
  }, [data, activeBrand?.id, activeBrand?.name, activeBrand?.logo_url]);

  return null;
}
